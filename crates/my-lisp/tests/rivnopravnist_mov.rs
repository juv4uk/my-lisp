use my_lisp::{eval_program, Session, Value};
use std::collections::HashSet;
use std::rc::Rc;

const РЕЄСТР: &str = include_str!("../../../lib/surface/semantic-registry.wsm");
const УКРАЇНСЬКА_ПОВЕРХНЯ: &str = include_str!("../../../lib/surface/uk.my");
const САНСКРИТСЬКА_ПОВЕРХНЯ: &str = include_str!("../../../lib/surface/sa.my");

#[derive(Debug)]
enum Форма {
    Атом(String),
    Список(Vec<Форма>),
}

fn лексеми(джерело: &str) -> Vec<String> {
    let без_коментарів = джерело
        .lines()
        .map(|рядок| рядок.split(';').next().unwrap_or_default())
        .collect::<Vec<_>>()
        .join("\n");

    let mut результат = Vec::new();
    let mut атом = String::new();

    for символ in без_коментарів.chars() {
        match символ {
            '(' | ')' => {
                if !атом.is_empty() {
                    результат.push(std::mem::take(&mut атом));
                }
                результат.push(символ.to_string());
            }
            символ if символ.is_whitespace() => {
                if !атом.is_empty() {
                    результат.push(std::mem::take(&mut атом));
                }
            }
            _ => атом.push(символ),
        }
    }

    if !атом.is_empty() {
        результат.push(атом);
    }

    результат
}

fn прочитати_форму(лексеми: &[String], позиція: &mut usize) -> Форма {
    let лексема = лексеми
        .get(*позиція)
        .unwrap_or_else(|| panic!("реєстр обірвався посеред форми"));
    *позиція += 1;

    if лексема != "(" {
        assert_ne!(лексема, ")", "неочікувана закривальна дужка");
        return Форма::Атом(лексема.clone());
    }

    let mut елементи = Vec::new();
    while лексеми.get(*позиція).map(String::as_str) != Some(")") {
        assert!(
            *позиція < лексеми.len(),
            "у семантичному реєстрі є незакритий список"
        );
        елементи.push(прочитати_форму(лексеми, позиція));
    }
    *позиція += 1;
    Форма::Список(елементи)
}

fn корінь_реєстру() -> Форма {
    let всі_лексеми = лексеми(РЕЄСТР);
    let mut позиція = 0;
    let корінь = прочитати_форму(&всі_лексеми, &mut позиція);
    assert_eq!(
        позиція,
        всі_лексеми.len(),
        "реєстр повинен містити рівно одну верхньорівневу форму"
    );
    корінь
}

fn записи_реєстру(корінь: &Форма) -> &[Форма] {
    let Форма::Список(елементи) = корінь else {
        panic!("семантичний реєстр повинен бути списком");
    };
    let Some(Форма::Атом(заголовок)) = елементи.first() else {
        panic!("семантичний реєстр не має заголовка");
    };
    assert_eq!(заголовок, "sr/1", "очікується схема sr/1");
    &елементи[1..]
}

fn атом(форма: &Форма) -> &str {
    let Форма::Атом(значення) = форма else {
        panic!("очікувався атом у семантичному реєстрі");
    };
    значення
}

fn поверхні(запис: &Форма) -> (&str, &[Форма]) {
    let Форма::Список(поля) = запис else {
        panic!("semantic identity повинна бути списком");
    };
    assert!(поля.len() >= 2, "semantic identity не має мовних поверхонь");
    (атом(&поля[0]), &поля[1..])
}

fn поля_поверхні(форма: &Форма) -> (&str, &str, &str) {
    let Форма::Список(поля) = форма else {
        panic!("опис мовної поверхні повинен бути списком");
    };
    assert_eq!(
        поля.len(),
        3,
        "опис мовної поверхні повинен мати форму (мова назва стан)"
    );
    (атом(&поля[0]), атом(&поля[1]), атом(&поля[2]))
}

fn перевірити_той_самий_builtin(ліве: &Value, праве: &Value) {
    match (ліве, праве) {
        (Value::Builtin(ліве), Value::Builtin(праве)) => assert!(
            Rc::ptr_eq(ліве, праве),
            "мовні назви повинні вказувати на один і той самий builtin"
        ),
        інше => panic!("очікувалися два builtin-значення, отримано {інше:?}"),
    }
}

#[test]
fn семантичні_ідентифікатори_складаються_тільки_з_цифр() {
    let корінь = корінь_реєстру();
    for запис in записи_реєстру(&корінь) {
        let (ідентифікатор, _) = поверхні(запис);
        assert!(
            ідентифікатор.len() >= 4
                && ідентифікатор.chars().all(|символ| символ.is_ascii_digit()),
            "семантичний ID {ідентифікатор:?} порушує мовну нейтральність"
        );
    }
}

#[test]
fn кожна_тотожність_має_рівно_три_рівноправні_поверхні_першої_хвилі() {
    let корінь = корінь_реєстру();
    let очікувані = HashSet::from(["uk", "en", "sa"]);

    for запис in записи_реєстру(&корінь) {
        let (ідентифікатор, описи) = поверхні(запис);
        let мови = описи
            .iter()
            .map(|опис| поля_поверхні(опис).0)
            .collect::<HashSet<_>>();

        assert_eq!(
            описи.len(),
            3,
            "{ідентифікатор}: кожна identity першої хвилі повинна явно описати UK, EN і SA"
        );
        assert_eq!(
            мови, очікувані,
            "{ідентифікатор}: жодна з трьох мов не може бути неявною або привілейованою"
        );
    }
}

#[test]
fn людська_назва_не_може_бути_машинним_ідентифікатором() {
    let корінь = корінь_реєстру();
    for запис in записи_реєстру(&корінь) {
        let (ідентифікатор, описи) = поверхні(запис);
        for опис in описи {
            let (мова, назва, _) = поля_поверхні(опис);
            assert_ne!(
                назва, ідентифікатор,
                "{ідентифікатор}/{мова}: людська surface name не повинна підміняти numeric identity"
            );
        }
    }
}

#[test]
fn додавання_має_одне_значення_для_української_англійської_і_санскриту() {
    let mut сесія = Session::default();

    let українське = eval_program("додати", &mut сесія)
        .expect("українська назва 0104 повинна існувати")
        .value;
    let англійське = eval_program("+", &mut сесія)
        .expect("англійська назва 0104 повинна існувати")
        .value;
    let санскритське = eval_program("yoga", &mut сесія)
        .expect("санскритська назва 0104 повинна існувати")
        .value;

    перевірити_той_самий_builtin(&українське, &англійське);
    перевірити_той_самий_builtin(&англійське, &санскритське);

    for вираз in ["(додати 20 22)", "(+ 20 22)", "(yoga 20 22)"] {
        assert_eq!(
            eval_program(вираз, &mut сесія).unwrap().value.to_string(),
            "42",
            "усі три назви 0104 повинні мати однакову поведінку"
        );
    }
}

#[test]
fn затінення_однієї_звичайної_назви_не_переналаштовує_інші_мови() {
    for (затінена, перша_сусідня, друга_сусідня) in [
        ("додати", "+", "yoga"),
        ("+", "додати", "yoga"),
        ("yoga", "додати", "+"),
    ] {
        let mut сесія = Session::default();
        eval_program(
            &format!("(define {затінена} (lambda (a b) (quote затінено)))"),
            &mut сесія,
        )
        .expect("ordinary peer name повинна лишатися лексично затінюваною");

        assert_eq!(
            eval_program(&format!("({затінена} 1 2)"), &mut сесія)
                .unwrap()
                .value
                .to_string(),
            "затінено"
        );
        assert_eq!(
            eval_program(&format!("({перша_сусідня} 1 2)"), &mut сесія)
                .unwrap()
                .value
                .to_string(),
            "3"
        );
        assert_eq!(
            eval_program(&format!("({друга_сусідня} 1 2)"), &mut сесія)
                .unwrap()
                .value
                .to_string(),
            "3"
        );
    }
}

